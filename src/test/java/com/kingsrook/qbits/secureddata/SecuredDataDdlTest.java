/*******************************************************************************
 ** Secured data ddl test.
 *******************************************************************************/
class SecuredDataDdlTest
{



   /*******************************************************************************
    ** Cleanup.
    *******************************************************************************/
   @AfterEach
   void cleanup()
   {
      close();
   }

   /*******************************************************************************
    ** Postgres ddl runs in h2and supports actual qqq writes.
    *******************************************************************************/
   @Test
   void postgresDdlRunsInH2AndSupportsActualQqqWrites() throws Exception
   {
      String url = "jdbc:h2:mem:secured_data;MODE=PostgreSQL;DATABASE_TO_UPPER=FALSE;DB_CLOSE_DELAY=-1";
      try(Connection connection = DriverManager.getConnection(url, "sa", ""))
      {
         String ddl = Files.readString(Path.of("docs/ddl/secured-data-postgres.sql"));
         for(String sql : ddl.split(";"))
         {
            if(!sql.isBlank())
            {
               connection.createStatement().execute(sql);
            }
         }
         RDBMSBackendMetaData backend = new RDBMSBackendMetaData().withName("rdbms").withVendor("h2").withHostName("mem")
            .withDatabaseName("secured_data").withUsername("sa");
         backend.setJdbcUrl(url);
         QInstance instance = base();
         instance.addBackend(backend);
         instance.addTable(person("rdbms").withBackendDetails(new RDBMSTableBackendDetails().withTableName("person")));
         connection.createStatement().execute("CREATE TABLE person (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email VARCHAR(255), ssn VARCHAR(255), notes TEXT)");
         new SecuredDataQBitProducer().withQBitConfig(new SecuredDataQBitConfig().withBackendName("rdbms").withClock(CLOCK)
            .withAccessLogFlushIntervalMillis(60000).withTableMetaDataCustomizer((i, t) -> t.withBackendDetails(new RDBMSTableBackendDetails().withTableName(t.getName())))).produce(instance);
         QContext.init(instance, user("u1", "cs_admin"));
         RUNTIMES.add(SecuredDataRuntime.current());
         classification(null, "PII");
         policy("cs_admin", "PII", "REVEALABLE");
         assertThat(SecuredDataRuntime.current().resolver().resolve(instance.getTable("person"), instance.getTable("person").getField("email")).tier().name()).isEqualTo("REVEALABLE");
         SecuredDataRuntime.current().logger().onAccess(SecuredDataAccessLoggerTest.event(com.kingsrook.qbits.secureddata.standin.FieldAccessEventType.EXACT_MATCH_FILTER,
            com.kingsrook.qbits.secureddata.standin.FieldAccessOutcome.MATCH, "hmac"));
         SecuredDataRuntime.current().logger().flush();
         assertThat(logs()).hasSize(1);
         assertThatThrownBy(() -> connection.createStatement().execute("INSERT INTO secured_data_classification (table_name, classification) VALUES ('person', 'PHI')"))
            .isInstanceOf(java.sql.SQLException.class);
         assertThatThrownBy(() -> connection.createStatement().execute("INSERT INTO secured_data_policy (name, permission_name, classification, tier, reveal_minutes) VALUES ('x','x','PII','FULL',61)"))
            .isInstanceOf(java.sql.SQLException.class);
      }
   }
}
